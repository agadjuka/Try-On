"""
Инструмент CallManager для вызова менеджера
"""
import logging
from pydantic import BaseModel, Field
from langchain_core.tools import tool

logger = logging.getLogger(__name__)


class CallManagerInput(BaseModel):
    """Входные параметры для CallManager"""
    reason: str = Field(
        description="Причина вызова менеджера. ОБЯЗАТЕЛЬНО укажи конкретную причину, почему нужна помощь менеджера (например: 'Клиент хочет отменить запись, но не может указать номер телефона', 'Клиент задал вопрос о скидках, на который у меня нет информации', 'Техническая ошибка при создании записи')."
    )


@tool(args_schema=CallManagerInput)
def call_manager_tool(reason: str) -> str:
    """
    Вызвать менеджера для помощи клиенту.
    Используй когда не можешь ответить на вопрос, возникла техническая проблема,
    клиент просит что-то, требующее вмешательства менеджера, или клиент чем то недоволен.
    
    ВАЖНО: После вызова этого инструмента НЕ пиши никаких сообщений клиенту.
    """
    return f"Менеджер вызван. Причина: {reason}"

